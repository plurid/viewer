import { gzipSync } from 'node:zlib';
import { zipSync, strToU8 } from 'fflate';
import type { Zippable } from 'fflate';
import type { Sample } from '../types';

const epoch = new Date('2026-01-01T00:00:00Z');
export function zip(entries: Record<string, string | Uint8Array>): Uint8Array {
  const files: Zippable = {};
  for (const [name, content] of Object.entries(entries)) {
    const bytes = typeof content === 'string' ? strToU8(content) : content;
    // EPUB requires the first mimetype entry to be stored without compression.
    files[name] = name === 'mimetype' ? [bytes, { level: 0 }] : bytes;
  }
  return zipSync(files, { mtime: epoch });
}

export function sample(
  path: string,
  formats: string[],
  preview: string,
  description: string,
  bytes: Sample['bytes'],
): Sample {
  return {
    path,
    formats,
    preview,
    description,
    source: 'Generated by Viewer tools/playground; fictional content.',
    license: 'CC0-1.0',
    bytes,
  };
}

function pdf(): Uint8Array {
  const bodies = [
    '<< /Type /Catalog /Pages 2 0 R /Outlines 10 0 R >>',
    '<< /Type /Pages /Kids [3 0 R 5 0 R 7 0 R] /Count 3 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 9 0 R >> >> /Contents 4 0 R >>',
    '',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 9 0 R >> >> /Contents 6 0 R >>',
    '',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 9 0 R >> >> /Contents 8 0 R >>',
    '',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    '<< /Type /Outlines /First 11 0 R /Last 13 0 R /Count 3 >>',
    '<< /Title (Project brief) /Parent 10 0 R /Dest [3 0 R /Fit] /Next 12 0 R >>',
    '<< /Title (Materials) /Parent 10 0 R /Dest [5 0 R /Fit] /Prev 11 0 R /Next 13 0 R >>',
    '<< /Title (Review checklist) /Parent 10 0 R /Dest [7 0 R /Fit] /Prev 12 0 R >>',
  ];
  const pages = [
    [
      'FIELD NOTES / 01',
      'A spatial project brief',
      'A three-page synthetic document for PDF navigation.',
      'Search for aluminum, compare pages, then open the outline.',
      'All measurements and project names are fictional.',
    ],
    [
      'MATERIALS / 02',
      'Small objects, clear details',
      'Part                 Material             Quantity',
      'Front panel          Aluminum             12',
      'Spacer               Nylon                24',
      'Bracket              Steel                 6',
      'The reference panel is 200 by 100 millimeters.',
    ],
    [
      'REVIEW / 03',
      'Keep the evidence nearby',
      '1. Open this PDF beside the CAD panel.',
      '2. Find aluminum with the PDF search control.',
      '3. Select a sentence and inspect the thumbnails.',
      '4. Close the child plane and return to its folder.',
    ],
  ];
  pages.forEach((lines, index) => {
    const text = lines
      .map(
        (line, lineIndex) =>
          `${lineIndex === 1 ? '22' : '12'} Tf ${lineIndex ? '0 -36 Td ' : ''}(${line}) Tj`,
      )
      .join('\n/F1 ');
    const stream = `0.12 0.22 0.28 rg\nBT /F1 ${text} ET`;
    // Set a readable initial text origin before the content commands.
    const positioned = stream.replace('BT /F1', 'BT 64 716 Td /F1');
    bodies[3 + index * 2] =
      `<< /Length ${Buffer.byteLength(positioned)} >>\nstream\n${positioned}\nendstream`;
  });
  let bytes = '%PDF-1.4\n';
  const offsets = [0];
  for (const [index, body] of bodies.entries()) {
    offsets.push(Buffer.byteLength(bytes));
    bytes += `${index + 1} 0 obj\n${body}\nendobj\n`;
  }
  const xref = Buffer.byteLength(bytes);
  bytes += `xref\n0 ${bodies.length + 1}\n0000000000 65535 f \n`;
  bytes += offsets
    .slice(1)
    .map((offset) => `${String(offset).padStart(10, '0')} 00000 n \n`)
    .join('');
  bytes += `trailer\n<< /Size ${bodies.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(bytes);
}

