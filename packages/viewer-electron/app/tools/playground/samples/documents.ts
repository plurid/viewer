function tar(entries: Record<string, string>): Uint8Array {
  const parts: Buffer[] = [];
  for (const [name, text] of Object.entries(entries)) {
    const data = Buffer.from(text);
    const header = Buffer.alloc(512);
    header.write(name);
    header.write('0000644\0', 100);
    header.write('0000000\0', 108);
    header.write('0000000\0', 116);
    header.write(data.length.toString(8).padStart(11, '0') + '\0', 124);
    header.write('00000000000\0', 136);
    header.fill(32, 148, 156);
    header.write('0', 156);
    header.write('ustar\0', 257);
    header.write('00', 263);
    const checksum = header.reduce((sum, byte) => sum + byte, 0);
    header.write(checksum.toString(8).padStart(6, '0') + '\0 ', 148);
    parts.push(header, data, Buffer.alloc((512 - (data.length % 512)) % 512));
  }
  return Buffer.concat([...parts, Buffer.alloc(1024)]);
}

function djvu(jpeg: Uint8Array): Uint8Array {
  const chunk = (name: string, bytes: Uint8Array) => {
    const size = Buffer.alloc(4);
    size.writeUInt32BE(bytes.length);
    return Buffer.concat([Buffer.from(name), size, bytes, Buffer.alloc(bytes.length % 2)]);
  };
  const info = Buffer.alloc(10);
  info.writeUInt16BE(640);
  info.writeUInt16BE(480, 2);
  info[4] = 26;
  info.writeUInt16LE(100, 6);
  info[8] = 22;
  info[9] = 1;
  const body = Buffer.concat([Buffer.from('DJVU'), chunk('INFO', info), chunk('BGjp', jpeg)]);
  const size = Buffer.alloc(4);
  size.writeUInt32BE(body.length);
  return Buffer.concat([Buffer.from('AT&TFORM'), size, body]);
}

