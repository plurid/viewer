import { describe, expect, it } from 'vitest';
import {
  formatSubtitleDuration,
  formatSubtitleTime,
  parseSubtitles,
  subtitleFormat,
  subtitleTime,
  subtitlesToVTT,
} from '../src/domain/previews/data/subtitles';

// SubRip as players meet it: CRLF, a BOM, commas in times, tags, and one missing blank line.
const srt = [
  '﻿1',
  '00:00:01,000 --> 00:00:04,250',
  '<i>Previously</i> on <font color="#ffff00">Viewer</font>…',
  '',
  '2',
  '00:00:05,5 --> 00:00:07,000 X1:100 X2:500 Y1:20 Y2:60',
  '{\\an8}Signs & <b>notices</b>',
  'second line',
  '3',
  '00:01:02,003 --> 00:01:04,000',
  'No blank line before this cue',
  '',
  'a stray block without a time',
  '',
  '4',
  '01:32:08,000 --> 01:32:10,500',
  '- Is that 5 < 6?',
  '- Yes.',
  '',
].join('\r\n');

const vtt = [
  'WEBVTT - Episode 1',
  'Kind: captions',
  'Language: en',
  '',
  'STYLE',
  '::cue { color: yellow }',
  '',
  'NOTE This note has',
  'two lines and no cue',
  '',
  'intro',
  '00:01.000 --> 00:04.000 line:0 align:start',
  '<v Ana>Hello &amp; welcome</v>',
  '',
  '00:00:05.000 --> 00:00:06.500 position:10%',
  '<c.loud>Two</c> <b>tags</b> &lt;3',
  '',
  'broken',
  'not a timing line',
  '',
].join('\n');

const ass = [
  '[Script Info]',
  '; Script generated by Aegisub',
  'Title: Pilot',
  'ScriptType: v4.00+',
  '',
  '[V4+ Styles]',
  'Format: Name, Fontname, Fontsize, PrimaryColour, Bold, Italic',
  'Style: Default,Arial,20,&H00FFFFFF,0,0',
  '',
  '[Events]',
  'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
  'Dialogue: 0,0:00:05.00,0:00:07.50,Default,Ana,0,0,0,,{\\i1}Later{\\i0}, she said\\Nfar away',
  'Comment: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,not shown',
  'Dialogue: 0,0:00:01.00,0:00:03.00,Sign,,0,0,0,,{\\an8\\b1\\fs40\\pos(320,40)}TOP SIGN',
  'Dialogue: 1,0:00:01.00,0:00:03.00,Default,,0,0,0,,{\\p1}m 0 0 l 100 0 100 100{\\p0}Hard\\hspace',
  'Dialogue: 0,bad,0:00:09.00,Default,,0,0,0,,unreadable',
].join('\n');

describe('subtitle times', () => {
  it('reads each format and writes WebVTT times and durations', () => {
    expect(subtitleTime('00:00:01,000')).toBe(1000);
    expect(subtitleTime('01:02.500')).toBe(62_500);
    expect(subtitleTime('1:02:03.45')).toBe(3_723_450);
    expect(subtitleTime('00:61:00,000')).toBeUndefined();
    expect(formatSubtitleTime(5_530_500)).toBe('01:32:10.500');
    expect(formatSubtitleTime(1_250, ',')).toBe('00:00:01,250');
    expect(formatSubtitleDuration(5_530_500)).toBe('1:32:10');
    expect(formatSubtitleDuration(245_000)).toBe('4:05');
  });

  it('chooses the format from content, then the extension', () => {
    expect(subtitleFormat('srt', srt)).toBe('srt');
    expect(subtitleFormat('txt', vtt)).toBe('vtt');
    expect(subtitleFormat('txt', ass)).toBe('ass');
    expect(subtitleFormat('SSA')).toBe('ass');
    expect(subtitleFormat('txt', 'plain')).toBeUndefined();
  });
});

describe('subtitle cues', () => {
  it('reads SubRip cues with commas in times and strips their markup', () => {
    const parsed = parseSubtitles(srt, 'srt');
    expect(parsed.cues.map(({ id, start, end, text }) => ({ id, start, end, text }))).toEqual([
      { id: '1', start: 1000, end: 4250, text: 'Previously on Viewer…' },
      { id: '2', start: 5500, end: 7000, text: 'Signs & notices\nsecond line' },
      { id: '3', start: 62_003, end: 64_000, text: 'No blank line before this cue' },
      { id: '4', start: 5_528_000, end: 5_530_500, text: '- Is that 5 < 6?\n- Yes.' },
    ]);
    expect(parsed.cues.map((cue) => cue.index)).toEqual([1, 2, 3, 4]);
    expect(parsed.duration).toBe(5_530_500);
    expect(parsed.skipped).toBe(1);
  });

  it('reads WebVTT cues with identifiers, settings and voices, skipping other blocks', () => {
    const parsed = parseSubtitles(vtt, 'vtt');
    expect(parsed.title).toBe('- Episode 1');
    expect(parsed.cues).toEqual([
      {
        index: 1,
        id: 'intro',
        start: 1000,
        end: 4000,
        text: 'Hello & welcome',
        settings: 'line:0 align:start',
        style: undefined,
        speaker: 'Ana',
      },
      {
        index: 2,
        id: undefined,
        start: 5000,
        end: 6500,
        text: 'Two tags <3',
        settings: 'position:10%',
        style: undefined,
        speaker: undefined,
      },
    ]);
    expect(parsed.skipped).toBe(1);
  });

  it('reads ASS dialogue in time order with override tags and drawings removed', () => {
    const parsed = parseSubtitles(ass, 'ass');
    expect(parsed.title).toBe('Pilot');
    expect(
      parsed.cues.map(({ start, end, text, style, speaker }) => ({
        start,
        end,
        text,
        style,
        speaker,
      })),
    ).toEqual([
      { start: 1000, end: 3000, text: 'TOP SIGN', style: 'Sign', speaker: undefined },
      { start: 1000, end: 3000, text: 'Hard space', style: 'Default', speaker: undefined },
      {
        start: 5000,
        end: 7500,
        text: 'Later, she said\nfar away',
        style: 'Default',
        speaker: 'Ana',
      },
    ]);
    expect(parsed.skipped).toBe(1);
    expect(parsed.duration).toBe(7500);
  });

  it('bounds the cues it reads', () => {
    const many = Array.from(
      { length: 5 },
      (_, index) => `${index + 1}\n00:00:0${index},000 --> 00:00:0${index},500\nLine ${index}\n`,
    ).join('\n');
    const parsed = parseSubtitles(many, 'srt', { cues: 3 });
    expect(parsed.cues).toHaveLength(3);
    expect(parsed.truncated).toBe(true);
  });
});

describe('WebVTT conversion', () => {
  it('converts SubRip, keeping basic styling and escaping text', () => {
    expect(subtitlesToVTT(srt, 'srt')).toBe(
      [
        'WEBVTT',
        '',
        '1',
        '00:00:01.000 --> 00:00:04.250',
        '<i>Previously</i> on Viewer…',
        '',
        '2',
        '00:00:05.500 --> 00:00:07.000 line:0',
        'Signs &amp; <b>notices</b>',
        'second line',
        '',
        '3',
        '00:01:02.003 --> 00:01:04.000',
        'No blank line before this cue',
        '',
        '4',
        '01:32:08.000 --> 01:32:10.500',
        '- Is that 5 &lt; 6?',
        '- Yes.',
        '',
      ].join('\n'),
    );
  });

  it('converts ASS overrides to WebVTT tags and placement', () => {
    expect(subtitlesToVTT(ass, 'ass')).toBe(
      [
        'WEBVTT',
        '',
        '00:00:01.000 --> 00:00:03.000 line:0',
        '<b>TOP SIGN</b>',
        '',
        '00:00:01.000 --> 00:00:03.000',
        'Hard space',
        '',
        '00:00:05.000 --> 00:00:07.500',
        '<i>Later</i>, she said',
        'far away',
        '',
      ].join('\n'),
    );
  });

  it('keeps WebVTT as written and never lets cue text end a cue early', () => {
    expect(subtitlesToVTT(vtt.replace(/\n/g, '\r\n'), 'vtt')).toBe(vtt);
    expect(subtitlesToVTT('1\n00:00:01,000 --> 00:00:02,000\nA --> B\n', 'srt')).toBe(
      'WEBVTT\n\n1\n00:00:01.000 --> 00:00:02.000\nA --&gt; B\n',
    );
    expect(
      subtitlesToVTT('[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,D,,0,0,0,,One\\N\\NTwo', 'ass'),
    ).toBe('WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nOne\nTwo\n');
  });
});
