/** One line people can read: composed characters, and a space for each control character. */
export const plainText = (text: string) =>
  text
    .normalize('NFC')
    .replace(/[\u0000-\u001f\u007f-\u009f]/g, ' ')
    .replace(/[\ud800-\udbff](?![\udc00-\udfff])|(?<![\ud800-\udbff])[\udc00-\udfff]/g, '�');

/** The WinAnsi code of each character, or undefined when one falls outside WinAnsi. */
function codes(text: string): number[] | undefined {
  const found: number[] = [];
  for (const character of text) {
    const point = character.codePointAt(0)!;
    const code =
      (point >= 0x20 && point <= 0x7e) || (point >= 0xa0 && point <= 0xff)
        ? point
        : winAnsiExtras.get(point);
    if (code === undefined) return undefined;
    found.push(code);
  }
  return found;
}
export const inWinAnsi = (text: string) => codes(text) !== undefined;

/** A WinAnsi line's width in points, without kerning, as standard fonts are drawn. */
export function helveticaWidth(text: string, size: number, weight: TextWeight): number {
  const table = helveticaWidths[weight];
  const total = (codes(text) ?? []).reduce((sum, code) => sum + (table[code - 32] ?? 0), 0);
  return (total * size) / 1000;
}

/**
 * A WinAnsi line as the writer draws it within `maxWidth`: whole when it fits, otherwise its
 * longest start, less trailing spaces, with an ellipsis; undefined when not even the ellipsis fits.
 */
export function fitHelvetica(
  text: string,
  size: number,
  weight: TextWeight,
  maxWidth: number | undefined,
): string | undefined {
  if (maxWidth === undefined || helveticaWidth(text, size, weight) <= maxWidth) return text;
  const characters = [...text];
  const shortened = (length: number) =>
    characters.slice(0, length).join('').replace(/ +$/, '') + '…';
  if (helveticaWidth(shortened(0), size, weight) > maxWidth) return undefined;
  let low = 0;
  let high = characters.length - 1;
  while (low < high) {
    const middle = Math.ceil((low + high) / 2);
    if (helveticaWidth(shortened(middle), size, weight) <= maxWidth) low = middle;
    else high = middle - 1;
  }
  return shortened(low);
}
