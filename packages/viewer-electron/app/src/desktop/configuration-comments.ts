/**
 * Add guidance without reserializing values, user comments, formatting or trailing commas. In a
 * documented file, `added` limits it to the properties a write added: every save put back every
 * guide line a person had deleted (2026-10-20). Without `added`, every missing line is added.
 */
export function documentConfiguration(text: string, added?: ReadonlySet<string>): string {
  const documented = text.split(/\r?\n/).includes(guide);
  if (documented)
    for (const [earlier, current] of revisedGuidance) text = text.replace(earlier, current);
  const errors: ParseError[] = [];
  const root = parseTree(text, errors, { allowTrailingComma: true });
  if (!root || root.type !== 'object' || errors.length)
    throw new Error('Cannot document invalid JSONC configuration.');
  const comments = new Map<string, string[]>(
    Object.entries(descriptions).map(([key, lines]) => [key, [...lines]]),
  );
  for (const field of settingCatalog) {
    const lines = comments.get(field.path) || [field.detail || field.label + '.'];
    if (field.kind === 'choice')
      lines.push('Settings choices: ' + field.choices!.map(([value]) => value).join(' | ') + '.');
    if (field.min !== undefined && field.max !== undefined)
      lines.push(`Allowed range: ${field.min}-${field.max}.`);
    comments.set(field.path, lines);
  }
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const edits: Edit[] = documented
    ? []
    : [{ offset: 0, length: 0, content: introduction.join(eol) + eol }];
  const visit = (node: Node, keys: string[]) => {
    if (node.type !== 'object') return;
    for (const property of node.children || []) {
      const [key, value] = property.children!;
      if (!key || !value) continue;
      const next = [...keys, String(key.value)];
      const lines = comments.get(next.join('.'));
      if (lines) {
        const start = text.lastIndexOf('\n', property.offset - 1) + 1;
        const above: string[] = [];
        for (const line of text.slice(0, start).split(/\r?\n/).reverse()) {
          if (!line.trim()) continue;
          if (!line.trim().startsWith('//')) break;
          above.push(line.trim());
        }
        // New fields still get guidance when an already-documented config is patched.
        const isAdded =
          !added || next.some((_, index) => added.has(next.slice(0, index + 1).join('.')));
        const missingLines = documented
          ? isAdded
            ? lines.filter((line) => !above.includes('// ' + line))
            : []
          : lines;
        if (!missingLines.length) {
          visit(value, next);
          continue;
        }
        const prefix = text.slice(start, property.offset);
        const ownLine = /^[\t ]*$/.test(prefix);
        const indent = ownLine ? prefix : '  '.repeat(next.length);
        edits.push({
          offset: ownLine ? start : property.offset,
          length: 0,
          content:
            (ownLine ? '' : eol) +
            missingLines.map((line) => indent + '// ' + line).join(eol) +
            eol +
            (ownLine ? '' : indent),
        });
      }
      visit(value, next);
    }
  };
  visit(root, []);
  return applyEdits(text, edits);
}
